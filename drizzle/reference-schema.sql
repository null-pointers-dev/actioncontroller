CREATE TABLE cp.workflow_runs (
    run_id                  bigint      NOT NULL,
    run_attempt             int         NOT NULL,
    workspace_id            uuid        NOT NULL,
    workflow_id             bigint      NOT NULL,
    run_request_id          uuid        REFERENCES cp.run_requests(id),
    event                   text,
    display_title           text,
    head_branch             text,
    head_sha                text,
