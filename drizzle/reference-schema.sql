-- =====================================================================
--  Workflow Control Plane — PostgreSQL schema (v3: workspaces + token pool)
--
--  Target    : PostgreSQL 18 (Azure Database for PostgreSQL Flexible Server)
--  Owned by  : the app's `server/db` (Drizzle schema mirrors this file;
--              triggers/functions live in hand-written SQL migrations)
--  Verify    : psql -v ON_ERROR_STOP=1 -f schema.sql -f schema-checks.sql
--
--  What changed from the previous version
--    * A WORKSPACE is an imported GitHub repository. Only app admins import.
--    * Access = workspace visibility (private / public) + grants to users or
--      Entra ID groups. No GitHub-derived permissions.
--    * Identity = Microsoft Entra ID via Better Auth (schema "auth").
--      The user's GitHub username is stored for attribution only.
--    * GitHub is called through a POOL of credentials (PATs and/or GitHub App
--      installations). Rate limits are tracked per BUCKET (per GitHub account
--      or installation), because GitHub limits per account, not per token.
--    * Two process roles: web (Next.js) and worker. Ingest lives in web.
--    * Policies folded into per-workflow settings (approval, refs, concurrency).
--
--  Unchanged: intent vs mirror, state machine guard, forward-only GitHub status,
--  frozen WANTED, outbox events (append-only, commit-safe feed), Postgres work
--  queue + leases, webhook inbox dedupe.
-- =====================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS cp;

-- =====================================================================
-- 1. Vocabularies
-- =====================================================================

-- GitHub status (+ conclusion) -> rank. Never moves to a lower rank.
CREATE OR REPLACE FUNCTION cp.github_status_rank(p_status text, p_conclusion text)
RETURNS smallint LANGUAGE sql IMMUTABLE AS $$
    SELECT (CASE
        WHEN p_status = 'requested'                                     THEN 1
        WHEN p_status IN ('queued', 'pending')                          THEN 2
        WHEN p_status IN ('waiting', 'in_progress')                     THEN 3
        WHEN p_status = 'completed' AND p_conclusion = 'action_required' THEN 3
        WHEN p_status = 'completed'                                     THEN 5
        ELSE 0
    END)::smallint
$$;

-- Run-request state machine, as data.
CREATE OR REPLACE FUNCTION cp.phase_transition_allowed(p_from text, p_to text)
RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
    SELECT p_from = p_to OR (p_from, p_to) IN (
        ('pending','awaiting_approval'), ('pending','waiting_for_slot'), ('pending','dispatching'),
        ('pending','rejected'), ('pending','cancelled'),
        ('awaiting_approval','waiting_for_slot'), ('awaiting_approval','dispatching'),
        ('awaiting_approval','rejected'), ('awaiting_approval','cancelled'),
        ('waiting_for_slot','dispatching'), ('waiting_for_slot','rejected'), ('waiting_for_slot','cancelled'),
        ('dispatching','verifying'), ('dispatching','dispatched'), ('dispatching','running'),
        ('dispatching','succeeded'), ('dispatching','failed'), ('dispatching','cancelled'),
        ('dispatching','cancelling'), ('dispatching','lost'),
        ('verifying','dispatching'), ('verifying','dispatched'), ('verifying','running'),
        ('verifying','succeeded'), ('verifying','failed'), ('verifying','cancelled'),
        ('verifying','cancelling'), ('verifying','lost'),
        ('dispatched','running'), ('dispatched','succeeded'), ('dispatched','failed'),
        ('dispatched','cancelled'), ('dispatched','cancelling'),
        ('running','succeeded'), ('running','failed'), ('running','cancelled'), ('running','cancelling'),
        ('cancelling','cancelled'), ('cancelling','succeeded'), ('cancelling','failed')
    )
$$;

-- =====================================================================
-- 2. Identity — Better Auth tables (schema "auth")
--    Configure Better Auth with modelName users/sessions/accounts/verifications,
--    UUID ids generated by the database, and the additional user fields below.
--    The Better Auth CLI output must match this shape (checked in CI).
-- =====================================================================

CREATE TABLE auth.users (
    id                      uuid        PRIMARY KEY DEFAULT uuidv7(),
    name                    text        NOT NULL,
    email                   text        NOT NULL UNIQUE,
    email_verified          boolean     NOT NULL DEFAULT false,
    image                   text,
    -- additional fields (ours)
    role                    text        NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_active               boolean     NOT NULL DEFAULT true,
    entra_object_id         text        UNIQUE,                 -- Entra "oid" (stable)
    github_user_id          bigint      UNIQUE,                 -- stable key on GitHub
    github_login            text,                               -- refreshed; can change on rename
    github_avatar_url       text,
    github_identity_source  text        CHECK (github_identity_source IN ('saml', 'self_declared', 'admin')),
    github_synced_at        timestamptz,
    last_login_at           timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CHECK ((github_user_id IS NULL) = (github_login IS NULL))
);

CREATE TABLE auth.sessions (
    id          uuid        PRIMARY KEY DEFAULT uuidv7(),
    token       text        NOT NULL UNIQUE,
    user_id     uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL,
    ip_address  text,
    user_agent  text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_user_idx ON auth.sessions (user_id);

CREATE TABLE auth.accounts (
    id                        uuid        PRIMARY KEY DEFAULT uuidv7(),
    account_id                text        NOT NULL,            -- Entra oid for provider 'microsoft'
    provider_id               text        NOT NULL,            -- 'microsoft'
    user_id                   uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    access_token              text,
    refresh_token             text,
    id_token                  text,
    access_token_expires_at   timestamptz,
    refresh_token_expires_at  timestamptz,
    scope                     text,
    password                  text,
    created_at                timestamptz NOT NULL DEFAULT now(),
    updated_at                timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider_id, account_id)
);
CREATE INDEX accounts_user_idx ON auth.accounts (user_id);

CREATE TABLE auth.verifications (
    id          uuid        PRIMARY KEY DEFAULT uuidv7(),
    identifier  text        NOT NULL,
    value       text        NOT NULL,
    expires_at  timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Entra ID groups seen in users' tokens (synced at every login).
CREATE TABLE cp.directory_groups (
    id            text        PRIMARY KEY,                     -- Entra group object id
    display_name  text,
    last_seen_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cp.user_groups (
    user_id    uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    group_id   text        NOT NULL REFERENCES cp.directory_groups(id) ON DELETE CASCADE,
    synced_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, group_id)
);
CREATE INDEX user_groups_group_idx ON cp.user_groups (group_id);

-- =====================================================================
-- 3. GitHub credential pool
--    Secrets are NEVER stored here: secret_ref names a Key Vault secret.
--    rate_bucket groups credentials that share one GitHub rate limit:
--      'user:<github account id>'      for personal access tokens
--      'installation:<installation id>' for GitHub App installations
-- =====================================================================

CREATE TABLE cp.github_credentials (
    id                    uuid        PRIMARY KEY DEFAULT uuidv7(),
    label                 text        NOT NULL UNIQUE,         -- 'release-bot PAT #2'
    kind                  text        NOT NULL CHECK (kind IN ('fine_grained_pat', 'classic_pat', 'github_app')),
    secret_ref            text        NOT NULL,                -- Key Vault secret name
    github_account_id     bigint,                              -- owner of a PAT
    github_account_login  text,
    app_id                bigint,                              -- for github_app
    installation_id       bigint,                              -- for github_app
    rate_bucket           text        NOT NULL,
    status                text        NOT NULL DEFAULT 'active'
                                      CHECK (status IN ('active', 'disabled', 'expired', 'invalid')),
    priority              smallint    NOT NULL DEFAULT 100,    -- lower = preferred
    expires_at            timestamptz,                         -- PAT expiry (from GitHub response header)
    last_used_at          timestamptz,
    last_error            text,
    consecutive_failures  int         NOT NULL DEFAULT 0,
    created_by            uuid        NOT NULL REFERENCES auth.users(id),
    resource_version      bigint      NOT NULL DEFAULT 1,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CHECK ((kind = 'github_app') = (installation_id IS NOT NULL AND app_id IS NOT NULL)),
    CHECK ((kind = 'github_app') OR github_account_id IS NOT NULL),
    CHECK (rate_bucket = CASE WHEN kind = 'github_app'
                              THEN 'installation:' || installation_id
                              ELSE 'user:' || github_account_id END)
);
CREATE INDEX github_credentials_active_idx ON cp.github_credentials (rate_bucket) WHERE status = 'active';

-- Live rate-limit state per bucket and GitHub "resource" (core, graphql, search, ...).
CREATE TABLE cp.github_rate_buckets (
    rate_bucket           text        NOT NULL,
    resource              text        NOT NULL DEFAULT 'core',
    limit_total           int,
    remaining             int,
    resets_at             timestamptz,
    blocked_until         timestamptz,                         -- secondary limit / Retry-After
    breaker_state         text        NOT NULL DEFAULT 'closed' CHECK (breaker_state IN ('closed', 'open', 'half_open')),
    consecutive_failures  int         NOT NULL DEFAULT 0,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (rate_bucket, resource)
);

-- =====================================================================
-- 4. Workspaces — one imported GitHub repository each
-- =====================================================================

CREATE TABLE cp.workspaces (
    id                 uuid        PRIMARY KEY DEFAULT uuidv7(),
    github_repo_id     bigint      NOT NULL UNIQUE,            -- stable across renames
    owner_login        text        NOT NULL,
    repo_name          text        NOT NULL,
    full_name          text        NOT NULL UNIQUE,            -- owner/name (refreshed on sync)
    default_branch     text        NOT NULL,
    display_name       text        NOT NULL,
    description        text,
    visibility         text        NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
    public_role        text        CHECK (public_role IN ('viewer', 'operator')),
    status             text        NOT NULL DEFAULT 'importing'
                                   CHECK (status IN ('importing', 'active', 'error', 'archived')),
    status_reason      text,
    update_mode        text        NOT NULL DEFAULT 'polling' CHECK (update_mode IN ('webhook', 'polling')),
    github_hook_id     bigint,                                 -- when we registered the repo webhook
    imported_by        uuid        NOT NULL REFERENCES auth.users(id),
    imported_at        timestamptz NOT NULL DEFAULT now(),
    last_synced_at     timestamptz,
    runs_listed_until  timestamptz,                            -- Checker "warm" checkpoint
    resource_version   bigint      NOT NULL DEFAULT 1,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CHECK ((visibility = 'public') = (public_role IS NOT NULL)),
    CHECK ((update_mode = 'webhook') = (github_hook_id IS NOT NULL))
);

-- Who may use a private workspace (and extra rights in a public one).
CREATE TABLE cp.workspace_grants (
    id             uuid        PRIMARY KEY DEFAULT uuidv7(),
    workspace_id   uuid        NOT NULL REFERENCES cp.workspaces(id) ON DELETE CASCADE,
    subject_type   text        NOT NULL CHECK (subject_type IN ('user', 'group')),
    subject_id     text        NOT NULL,                       -- users.id (uuid text) or Entra group id
    role           text        NOT NULL CHECK (role IN ('viewer', 'operator')),
    can_approve    boolean     NOT NULL DEFAULT false,
    environments   text[],                                     -- NULL = any (applies to operator)
    granted_by     uuid        NOT NULL REFERENCES auth.users(id),
    granted_at     timestamptz NOT NULL DEFAULT now(),
    expires_at     timestamptz,
    UNIQUE (workspace_id, subject_type, subject_id)
);
CREATE INDEX workspace_grants_subject_idx ON cp.workspace_grants (subject_type, subject_id);

-- Which pool credentials may serve a workspace (validated at import / re-validated on failure).
CREATE TABLE cp.workspace_credentials (
    workspace_id   uuid        NOT NULL REFERENCES cp.workspaces(id) ON DELETE CASCADE,
    credential_id  uuid        NOT NULL REFERENCES cp.github_credentials(id) ON DELETE CASCADE,
    can_dispatch   boolean     NOT NULL,                       -- Actions write verified
    validated_at   timestamptz NOT NULL DEFAULT now(),
    last_error     text,
    PRIMARY KEY (workspace_id, credential_id)
);
CREATE INDEX workspace_credentials_cred_idx ON cp.workspace_credentials (credential_id);

-- Workflows: discovered columns (worker) + curation and run settings (admins).
CREATE TABLE cp.workflows (
    id                     bigint      PRIMARY KEY,            -- GitHub workflow id
    workspace_id           uuid        NOT NULL REFERENCES cp.workspaces(id) ON DELETE CASCADE,
    -- discovered
    path                   text        NOT NULL,
    name                   text        NOT NULL,
    gh_state               text        NOT NULL,
    -- curation
    exposed                boolean     NOT NULL DEFAULT false,
    display_name           text,
    description            text,
    category               text,
    icon                   text,
    ui_schema              jsonb       NOT NULL DEFAULT '{}',
    -- run settings (formerly "policies")
    allowed_ref_patterns   text[],                             -- NULL = any ref
    approval_required      boolean     NOT NULL DEFAULT false,
    approval_environments  text[],                             -- NULL = all environments
    approval_min           smallint    NOT NULL DEFAULT 1 CHECK (approval_min BETWEEN 1 AND 5),
    approval_ttl           interval    NOT NULL DEFAULT interval '24 hours',
    concurrency_scope      text        NOT NULL DEFAULT 'none'
                                       CHECK (concurrency_scope IN ('none', 'workflow', 'workflow_environment')),
    concurrency_policy     text        NOT NULL DEFAULT 'allow' CHECK (concurrency_policy IN ('allow', 'forbid', 'queue')),
    resource_version       bigint      NOT NULL DEFAULT 1,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, path),
    CHECK ((concurrency_scope = 'none') = (concurrency_policy = 'allow'))
);
CREATE INDEX workflows_exposed_idx ON cp.workflows (workspace_id) WHERE exposed;

CREATE TABLE cp.workflow_definitions (
    workflow_id       bigint      NOT NULL REFERENCES cp.workflows(id) ON DELETE CASCADE,
    ref               text        NOT NULL,
    commit_sha        text        NOT NULL,
    has_dispatch      boolean     NOT NULL,
    input_schema      jsonb       NOT NULL DEFAULT '{"type":"object","properties":{}}',
    run_name_has_tag  boolean     NOT NULL,
    parse_problems    text[]      NOT NULL DEFAULT '{}',
    fetched_at        timestamptz NOT NULL DEFAULT now(),
    resource_version  bigint      NOT NULL DEFAULT 1,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workflow_id, ref)
);

-- =====================================================================
-- 5. Runs — intent (WANTED) and progress
-- =====================================================================

CREATE TABLE cp.run_requests (
    id                   uuid        PRIMARY KEY DEFAULT uuidv7(),
    correlation_tag      text        NOT NULL UNIQUE
                                     DEFAULT 'cp-' || substr(md5(gen_random_uuid()::text), 1, 12),
    idempotency_key      text        NOT NULL,
    -- WANTED (frozen)
    requested_by         uuid        NOT NULL REFERENCES auth.users(id),
    workspace_id         uuid        NOT NULL REFERENCES cp.workspaces(id),
    workflow_id          bigint      NOT NULL REFERENCES cp.workflows(id),
    ref                  text        NOT NULL,
    inputs               jsonb       NOT NULL DEFAULT '{}',
    environment          text,
    concurrency_key      text,
    concurrency_policy   text        NOT NULL DEFAULT 'allow' CHECK (concurrency_policy IN ('allow', 'forbid', 'queue')),
    settings_snapshot    jsonb       NOT NULL DEFAULT '{}',    -- approval/ref rules applied, for audit
    cancel_requested     boolean     NOT NULL DEFAULT false,
    cancel_requested_by  uuid        REFERENCES auth.users(id),
    cancel_requested_at  timestamptz,
    -- PROGRESS (worker)
    phase                text        NOT NULL DEFAULT 'pending' CHECK (phase IN (
                                       'pending', 'awaiting_approval', 'waiting_for_slot',
                                       'dispatching', 'verifying', 'dispatched', 'running', 'cancelling',
                                       'succeeded', 'failed', 'cancelled', 'rejected', 'lost')),
    phase_reason         text,
    phase_message        text,
    conditions           jsonb       NOT NULL DEFAULT '[]',
    github_run_id        bigint,
    dispatched_with      uuid        REFERENCES cp.github_credentials(id),  -- which credential sent it
    dispatch_attempts    smallint    NOT NULL DEFAULT 0,
    dispatch_sent_at     timestamptz,
    verify_until         timestamptz,
    resource_version     bigint      NOT NULL DEFAULT 1,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    UNIQUE (requested_by, idempotency_key),
    CHECK (concurrency_policy = 'allow' OR concurrency_key IS NOT NULL)
);
CREATE UNIQUE INDEX run_requests_github_run_uidx ON cp.run_requests (github_run_id) WHERE github_run_id IS NOT NULL;
CREATE INDEX run_requests_open_idx ON cp.run_requests (phase, updated_at)
    WHERE phase IN ('pending','awaiting_approval','waiting_for_slot','dispatching','verifying','dispatched','running','cancelling');
CREATE INDEX run_requests_by_requester_idx ON cp.run_requests (requested_by, created_at DESC);
CREATE INDEX run_requests_by_workspace_idx ON cp.run_requests (workspace_id, created_at DESC);
CREATE UNIQUE INDEX run_requests_one_active_per_slot ON cp.run_requests (concurrency_key)
    WHERE concurrency_policy IN ('forbid', 'queue')
      AND phase IN ('dispatching', 'verifying', 'dispatched', 'running', 'cancelling');

CREATE TABLE cp.run_actions (
    id                uuid        PRIMARY KEY DEFAULT uuidv7(),
    idempotency_key   text        NOT NULL,
    requested_by      uuid        NOT NULL REFERENCES auth.users(id),
    workspace_id      uuid        NOT NULL REFERENCES cp.workspaces(id),
    github_run_id     bigint      NOT NULL,
    run_attempt       int         NOT NULL,
    action            text        NOT NULL CHECK (action IN ('cancel', 'rerun_all', 'rerun_failed', 'rerun_job')),
    job_id            bigint,
    phase             text        NOT NULL DEFAULT 'pending' CHECK (phase IN ('pending', 'sending', 'done', 'failed', 'rejected')),
    phase_reason      text,
    result_attempt    int,
    resource_version  bigint      NOT NULL DEFAULT 1,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (requested_by, idempotency_key),
    CHECK ((action = 'rerun_job') = (job_id IS NOT NULL))
);
CREATE INDEX run_actions_open_idx ON cp.run_actions (phase, updated_at) WHERE phase IN ('pending', 'sending');

CREATE TABLE cp.approval_requests (
    run_request_id    uuid        PRIMARY KEY REFERENCES cp.run_requests(id),
    workspace_id      uuid        NOT NULL REFERENCES cp.workspaces(id),
    min_approvals     smallint    NOT NULL,
    state             text        NOT NULL DEFAULT 'pending'
                                  CHECK (state IN ('pending', 'approved', 'denied', 'expired', 'withdrawn')),
    expires_at        timestamptz NOT NULL,
    decided_at        timestamptz,
    resource_version  bigint      NOT NULL DEFAULT 1,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX approval_requests_pending_idx ON cp.approval_requests (workspace_id, expires_at) WHERE state = 'pending';

CREATE TABLE cp.approval_decisions (
    run_request_id  uuid        NOT NULL REFERENCES cp.approval_requests(run_request_id),
    approver_id     uuid        NOT NULL REFERENCES auth.users(id),
    decision        text        NOT NULL CHECK (decision IN ('approve', 'deny')),
    comment         text,
    decided_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_request_id, approver_id)
);

