CREATE OR REPLACE FUNCTION cp.enqueue(p_queue text, p_key text,
                                      p_delay interval DEFAULT interval '0', p_priority int DEFAULT 100)
RETURNS void LANGUAGE sql AS $$
    INSERT INTO cp.work_queue AS q (queue, key, run_after, priority)
    VALUES (p_queue, p_key, now() + p_delay, p_priority)
    ON CONFLICT (queue, key) DO UPDATE
       SET run_after = LEAST(q.run_after, EXCLUDED.run_after),
           priority  = LEAST(q.priority,  EXCLUDED.priority),
           dirty     = q.dirty OR COALESCE(q.locked_until > now(), false);
$$;

CREATE OR REPLACE FUNCTION cp.claim_work(p_queue text, p_worker text,
                                         p_limit int DEFAULT 10, p_lease interval DEFAULT interval '60 seconds')
RETURNS TABLE (work_key text, work_attempts int) LANGUAGE sql AS $$
    WITH next AS (
        SELECT q.queue, q.key FROM cp.work_queue q
         WHERE q.queue = p_queue AND q.run_after <= now()
           AND (q.locked_until IS NULL OR q.locked_until < now())
         ORDER BY q.priority, q.run_after
         LIMIT p_limit
         FOR UPDATE SKIP LOCKED
    )
    UPDATE cp.work_queue w
       SET locked_by = p_worker, locked_until = now() + p_lease, attempts = w.attempts + 1, dirty = false
      FROM next
     WHERE w.queue = next.queue AND w.key = next.key
    RETURNING w.key, w.attempts;
$$;

CREATE OR REPLACE FUNCTION cp.finish_work(p_queue text, p_key text, p_worker text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM cp.work_queue WHERE queue = p_queue AND key = p_key AND locked_by = p_worker AND NOT dirty;
    IF NOT FOUND THEN
        UPDATE cp.work_queue
           SET locked_by = NULL, locked_until = NULL, dirty = false, attempts = 0, run_after = now()
         WHERE queue = p_queue AND key = p_key AND locked_by = p_worker;
    END IF;
END
$$;

CREATE OR REPLACE FUNCTION cp.retry_work(p_queue text, p_key text, p_worker text, p_error text)
RETURNS void LANGUAGE sql AS $$
    UPDATE cp.work_queue
       SET locked_by = NULL, locked_until = NULL, last_error = p_error,
           run_after = now() + LEAST(interval '10 minutes', interval '1 second' * power(2, attempts)) * (0.5 + random())
     WHERE queue = p_queue AND key = p_key AND locked_by = p_worker;
$$;

CREATE OR REPLACE FUNCTION cp.acquire_lease(p_name text, p_holder text, p_ttl interval)
RETURNS bigint LANGUAGE sql AS $$
    INSERT INTO cp.leases AS l (name, holder, fencing_token, expires_at)
    VALUES (p_name, p_holder, 1, now() + p_ttl)
    ON CONFLICT (name) DO UPDATE
       SET fencing_token = CASE WHEN l.holder = EXCLUDED.holder THEN l.fencing_token ELSE l.fencing_token + 1 END,
           holder = EXCLUDED.holder, expires_at = EXCLUDED.expires_at
     WHERE l.holder = EXCLUDED.holder OR l.expires_at < now()
    RETURNING fencing_token;
$$;

CREATE OR REPLACE FUNCTION cp.ingest_webhook(p_guid uuid, p_event_type text, p_action text,
                                             p_github_repo_id bigint, p_payload jsonb)
RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO cp.inbox_seen (delivery_guid) VALUES (p_guid) ON CONFLICT DO NOTHING;
    IF NOT FOUND THEN
        RETURN false;
    END IF;
    INSERT INTO cp.webhook_deliveries (delivery_guid, event_type, action, github_repo_id, payload)
    VALUES (p_guid, p_event_type, p_action, p_github_repo_id, p_payload);
    PERFORM pg_notify('cp_inbox', p_event_type);
    RETURN true;
END
$$;

-- Commit-safe event feed: a cursor (txid, seq) can never skip an event.
CREATE OR REPLACE FUNCTION cp.read_events(p_after_txid xid8, p_after_seq bigint, p_limit int)
RETURNS SETOF cp.events LANGUAGE sql STABLE AS $$
    SELECT * FROM cp.events
     WHERE (txid, seq) > (p_after_txid, p_after_seq)
       AND txid < pg_snapshot_xmin(pg_current_snapshot())
     ORDER BY txid, seq
     LIMIT p_limit
$$;

-- Pick the best credential for a workspace: active, validated, bucket not blocked,
-- most remaining budget first, then priority. Returns NULL if none is usable.
CREATE OR REPLACE FUNCTION cp.pick_credential(p_workspace_id uuid, p_need_dispatch boolean, p_resource text DEFAULT 'core')
RETURNS uuid LANGUAGE sql STABLE AS $$
    SELECT c.id
      FROM cp.github_credentials c
      JOIN cp.workspace_credentials wc ON wc.credential_id = c.id AND wc.workspace_id = p_workspace_id
      LEFT JOIN cp.github_rate_buckets b ON b.rate_bucket = c.rate_bucket AND b.resource = p_resource
     WHERE c.status = 'active'
       AND (c.expires_at IS NULL OR c.expires_at > now())
       AND (NOT p_need_dispatch OR wc.can_dispatch)
       AND COALESCE(b.breaker_state, 'closed') <> 'open'
       AND (b.blocked_until IS NULL OR b.blocked_until < now())
       AND (b.remaining IS NULL OR b.remaining > 0 OR b.resets_at < now())
     ORDER BY CASE WHEN b.resets_at < now() THEN NULL ELSE b.remaining END DESC NULLS FIRST,
              c.priority, c.last_used_at NULLS FIRST
     LIMIT 1
$$;

CREATE OR REPLACE FUNCTION cp.ensure_month_partitions(p_parent text, p_months_ahead int DEFAULT 2)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    base timestamp := date_trunc('month', now() AT TIME ZONE 'UTC');
    i int; m_start timestamp; m_end timestamp;
BEGIN
    FOR i IN 0 .. p_months_ahead LOOP
        m_start := base + make_interval(months => i);
        m_end   := base + make_interval(months => i + 1);
        EXECUTE format('CREATE TABLE IF NOT EXISTS cp.%I PARTITION OF cp.%I FOR VALUES FROM (%L) TO (%L)',
                       p_parent || '_' || to_char(m_start, 'YYYY_MM'), p_parent,
                       m_start AT TIME ZONE 'UTC', m_end AT TIME ZONE 'UTC');
    END LOOP;
END
$$;

