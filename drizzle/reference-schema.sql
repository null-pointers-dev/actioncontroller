CREATE INDEX workflow_runs_unfinished_idx   ON cp.workflow_runs (last_seen_at) WHERE status <> 'completed';

CREATE TABLE cp.workflow_jobs (
    id                bigint      PRIMARY KEY,
    run_id            bigint      NOT NULL,
    run_attempt       int         NOT NULL,
    workspace_id      uuid        NOT NULL,
    name              text        NOT NULL,
    status            text        NOT NULL CHECK (status IN
                                    ('requested','queued','pending','waiting','in_progress','completed')),
    conclusion        text,
    status_rank       smallint    GENERATED ALWAYS AS (cp.github_status_rank(status, conclusion)) STORED,
    runner_name       text,
    labels            text[]      NOT NULL DEFAULT '{}',
    steps             jsonb       NOT NULL DEFAULT '[]',
    html_url          text,
    started_at        timestamptz,
    completed_at      timestamptz,
    last_seen_at      timestamptz NOT NULL DEFAULT now(),
    last_seen_via     text        NOT NULL CHECK (last_seen_via IN ('webhook', 'poll')),
    resource_version  bigint      NOT NULL DEFAULT 1,
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX workflow_jobs_by_run_idx ON cp.workflow_jobs (run_id, run_attempt);

